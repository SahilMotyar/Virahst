/**
 * Generates src/data/playlistTracks.ts from data/playlist.csv (an Exportify
 * export). Reads track name / artist / duration from the CSV and hydrates album
 * art once via Spotify's single-track endpoint (the only one open to app
 * tokens), so the running app needs neither Spotify credentials nor any runtime
 * API call. Re-run after re-exporting the playlist:
 *
 *   node scripts/gen-playlist.mjs
 *
 * Reads SPOTIFY_CLIENT_ID / SPOTIFY_CLIENT_SECRET from .env.local (optional —
 * without them, art is left null).
 */

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const CSV_PATH = join(root, "data", "playlist.csv");
const OUT_PATH = join(root, "src", "data", "playlistTracks.ts");

// --- tiny .env.local loader ----------------------------------------------
async function loadEnv() {
  try {
    const text = await readFile(join(root, ".env.local"), "utf8");
    for (const line of text.split(/\r?\n/)) {
      const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
      if (m && !process.env[m[1]]) process.env[m[1]] = m[2];
    }
  } catch {
    /* no .env.local — fine */
  }
}

// --- minimal CSV parser (quoted fields, embedded commas) -----------------
function parseCSV(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else inQuotes = false;
      } else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (c !== "\r") field += c;
  }
  if (field.length || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

async function getToken() {
  const id = process.env.SPOTIFY_CLIENT_ID;
  const secret = process.env.SPOTIFY_CLIENT_SECRET;
  if (!id || !secret) return null;
  const res = await fetch("https://accounts.spotify.com/api/token", {
    method: "POST",
    headers: {
      "Content-Type": "application/x-www-form-urlencoded",
      Authorization: `Basic ${Buffer.from(`${id}:${secret}`).toString("base64")}`,
    },
    body: "grant_type=client_credentials",
  });
  if (!res.ok) return null;
  return (await res.json()).access_token;
}

async function fetchArt(id, token) {
  const res = await fetch(`https://api.spotify.com/v1/tracks/${id}`, {
    headers: { Authorization: `Bearer ${token}` },
  });
  if (!res.ok) return null;
  const t = await res.json();
  return t.album?.images?.[0]?.url ?? null;
}

async function main() {
  await loadEnv();
  const csv = (await readFile(CSV_PATH, "utf8")).replace(/^﻿/, "");
  const rows = parseCSV(csv).filter((r) => r.length > 1);
  const header = rows.shift();
  const col = (name) => header.indexOf(name);
  const iUri = col("Track URI");
  const iName = col("Track Name");
  const iArtist = col("Artist Name(s)");
  const iDur = col("Duration (ms)");

  const token = await getToken();
  if (!token) {
    console.warn("⚠ No Spotify token (creds missing) — album art will be null.");
  }

  const tracks = [];
  for (const r of rows) {
    const uri = r[iUri];
    const id = uri?.split(":")[2];
    if (!id) continue;
    const name = r[iName];
    const artist = (r[iArtist] ?? "").split(";").map((s) => s.trim()).filter(Boolean).join(", ");
    const durationMs = Number(r[iDur]) || 0;
    const image = token ? await fetchArt(id, token) : null;
    tracks.push({ uri, name, artist, durationMs, image });
    console.log(`  ✓ ${name} — ${artist} ${image ? "🖼" : ""}`);
  }

  const body = `// AUTO-GENERATED by scripts/gen-playlist.mjs from data/playlist.csv.
// Do not edit by hand — re-run the script after re-exporting the playlist.

export interface PlaylistTrack {
  /** spotify:track:<id> — used to load the track for prev/next skipping. */
  uri: string;
  name: string;
  artist: string;
  /** Track length in milliseconds — used to match the currently-playing song. */
  durationMs: number;
  image: string | null;
}

export const playlistTracks: PlaylistTrack[] = ${JSON.stringify(tracks, null, 2)};
`;

  await writeFile(OUT_PATH, body, "utf8");
  console.log(`\nWrote ${tracks.length} tracks → ${OUT_PATH}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
